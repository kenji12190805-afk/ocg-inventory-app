/** コード補完の辞書の1項目 */
export interface Entry {
  /** 候補に出す名前(例: "for 〜 in range") */
  l: string;
  /** 入れるコードのひな形。${1:初期値} が書きかえる場所(穴)。${1} は同じ番号の穴と同じ文字になる */
  t: string;
  /** true のとき、穴(${…})の記法を使わず、そのままの文字として入れる(${ をそのまま書きたいとき) */
  raw?: boolean;
  /** 意味(やさしい日本語で) */
  m: string;
  /** この言葉にカーソルを置いたとき、この項目の意味を出す(識別子だけ) */
  w?: string[];
  /** この言葉でも候補に出す(日本語の言い換えなど) */
  a?: string[];
  /** 関数やクラスの定義・#include のように、関数の外に書くもの(検証用) */
  top?: boolean;
  /** 検証のときに、くりかえし/関数の中に入れる(break や return 用) */
  ctx?: 'loop' | 'func';
  /** 検証のときに、先に置くコード(elif や else 用) */
  pre?: string;
}
